async function main() {
  console.log('🌱 Seeding produits ChezPrecious...\n')

  for (const p of products) {
    const { images, variants, ...productData } = p

    const product = await prisma.product.upsert({
      where: { slug: productData.slug },
      update: {
        ...productData,
        price: productData.price,
        comparePrice: productData.comparePrice ?? undefined,
      },
      create: {
        ...productData,
        price: productData.price,
        comparePrice: productData.comparePrice ?? undefined,
      },
    })

    // Images
    await prisma.productImage.deleteMany({ where: { productId: product.id } })
    await prisma.productImage.createMany({
      data: images.map((img) => ({ ...img, productId: product.id })),
    })

    // Variants
    await prisma.productVariant.deleteMany({ where: { productId: product.id } })
    await prisma.productVariant.createMany({
      data: variants.map((v) => ({
        productId: product.id,
        combination: v.combination,
        price: v.price,
        stock: v.stock,
        isActive: v.stock > 0,
      })),
    })

    console.log(`  ✓ ${product.name} (${images.length} images, ${variants.length} variantes)`)
  }

  console.log('\n✅ Seed produits terminé !')
}

main()
  .catch((e) => {
    console.error('❌ Erreur :', e)
    process.exit(1)
  })
  .finally(() => prisma.$disconnect())
